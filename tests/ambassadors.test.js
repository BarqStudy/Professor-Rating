  calls.push({path,...options});
  if(path.startsWith('miyar_accounts'))return[{auth_id:student,university_id:3,status}];
  if(path.startsWith('miyar_ambassadors?'))return[{university_id:3}];
  if(path==='rpc/miyar_propose_catalogue')return{id:1,status:'pending'};
