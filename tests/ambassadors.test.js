import test from 'node:test';
import assert from 'node:assert/strict';
import { PGlite } from '@electric-sql/pglite';
import { readFile, readdir } from 'node:fs/promises';
import { createHandler } from '../supabase/functions/miyar/handler.js';
const student='11111111-1111-4111-8111-111111111111', ambassador='22222222-2222-4222-8222-222222222222', admin='33333333-3333-4333-8333-333333333333';

test('ambassador proposals and student corrections stay university-scoped, private and pending until atomic admin decisions',async()=>{
 const db=new PGlite();
 try{
  await db.exec('create role anon;create role authenticated;create role service_role bypassrls;create schema auth;create table auth.users(id uuid primary key,email text);');
  const dir=new URL('../supabase/migrations/',import.meta.url);
  for(const file of (await readdir(dir)).filter((name)=>name.endsWith('.sql')).sort())await db.exec(await readFile(new URL(file,dir),'utf8'));
  for(const [id,email] of [[student,'student@example.com'],[ambassador,'ambassador@example.com'],[admin,'admin@example.com']]){
   await db.query('insert into auth.users values($1,$2)',[id,email]);
   await db.query("insert into miyar_accounts(auth_id,name,university_id) values($1,'طالب',3)",[id]);
  }
  const rpc=async(name,args=[])=>(await db.query(`select ${name}(${args.map((_,index)=>'$'+(index+1)).join(',')}) as result`,args)).rows[0].result;
  const row=async(sql,args=[])=>(await db.query(sql,args)).rows[0];
  const propose=(who,kind,target,parent,name,staff=true,uni=3)=>rpc('miyar_propose_catalogue',[who,kind,uni,target,parent,name,'تصحيح معلومة في دليل الجامعة',staff]);
  const decide=(id,approve,reason='')=>rpc('miyar_decide_catalogue',[admin,id,approve,reason]);
  await assert.rejects(rpc('miyar_set_ambassador',[admin,'missing@example.com',3,true]),/AMBASSADOR_ACCOUNT_REQUIRED/);
  await assert.rejects(propose(ambassador,'college.add',null,null,'كلية العلوم'),/AMBASSADOR_SCOPE/);
  await rpc('miyar_set_ambassador',[admin,'AMBASSADOR@EXAMPLE.COM',3,true]);
  await rpc('miyar_set_ambassador',[admin,'ambassador@example.com',3,true]);
  assert.equal((await rpc('miyar_ambassador_list')).length,1);
  await assert.rejects(propose(ambassador,'college.add',null,null,'كلية العلوم',true,1),/AMBASSADOR_SCOPE/);
  await assert.rejects(propose(student,'college.add',null,null,'كلية العلوم',false),/AMBASSADOR_SCOPE/);
  const college=await propose(ambassador,'college.add',null,null,'كلية العلوم');
  assert.equal((await row("select count(*)::int as n from miyar_colleges where name='كلية العلوم'")).n,0);
  assert.equal((await rpc('miyar_catalogue_queue'))[0].ambassador,true);
  await decide(college.id,true);
  const collegeId=(await row("select id from miyar_colleges where name='كلية العلوم'")).id;
  assert.equal((await rpc('miyar_my_requests',[ambassador]))[0].status,'approved');
  assert.deepEqual(await rpc('miyar_my_requests',[student]),[]);
  const major=await propose(ambassador,'major.add',null,collegeId,'الفيزياء');
  await decide(major.id,true);
  const majorId=(await row("select id from miyar_majors where name='الفيزياء'")).id;
  const doctor=await propose(ambassador,'doctor.add',null,majorId,'أحمد محمد العتيبي');
  assert.equal((await row("select count(*)::int as n from miyar_doctors where name='أحمد محمد العتيبي'")).n,0);
  await decide(doctor.id,true);
  const doctorId=(await row("select id from miyar_doctors where name='أحمد محمد العتيبي'")).id;
  await db.query('update miyar_doctors set verified=true where id=$1',[doctorId]);
  const review=await rpc('miyar_submit_google_review',[student,'كلية العلوم','الفيزياء','أحمد محمد العتيبي','ميكانيكا',95,80,90,70,'',['يوصل المعلومة']]);
  await db.query("update miyar_reviews set status='published' where id=$1",[review.id]);
  const correction=await propose(student,'doctor.correct',doctorId,1,'أحمد محمد العتيبي المصحح',false);
  assert.equal((await row('select name from miyar_doctors where id=$1',[doctorId])).name,'أحمد محمد العتيبي');
  await assert.rejects(propose(student,'doctor.correct',doctorId,1,'أحمد محمد العتيبي المصحح',false),/unique constraint/);
  await decide(correction.id,true);
  const corrected=await row('select * from miyar_doctors where id=$1',[doctorId]);
  assert.equal(corrected.name,'أحمد محمد العتيبي المصحح');assert.equal(corrected.major_id,1);assert.equal(corrected.verified,true);
  assert.equal((await row('select doctor_id from miyar_reviews where id=$1',[review.id])).doctor_id,doctorId);
  assert.ok((await rpc('miyar_request_updates',[student])).some((event)=>event.kind==='catalogue'&&event.status==='approved'));
  const reject=await propose(student,'doctor.correct',doctorId,1,'أحمد محمد العتيبي الخاطئ',false);
  await assert.rejects(decide(reject.id,false,''),/REASON_REQUIRED/);
  await decide(reject.id,false,'الاسم الحالي مطابق للدليل الرسمي');
  assert.equal((await row('select name from miyar_doctors where id=$1',[doctorId])).name,corrected.name);
  assert.equal((await rpc('miyar_my_requests',[student])).find((request)=>request.id===reject.id).reason,'الاسم الحالي مطابق للدليل الرسمي');
  await assert.rejects(decide(reject.id,true),/REQUEST_NOT_FOUND/);
  await assert.rejects(propose(student,'doctor.correct',doctorId,1,corrected.name,false),/PROPOSAL_UNCHANGED/);
  const stale=await propose(student,'doctor.correct',doctorId,1,'أحمد محمد العتيبي الجديد',false);
  await db.query("update miyar_doctors set name='أحمد محمد العتيبي المعدل' where id=$1",[doctorId]);
  await assert.rejects(decide(stale.id,true),/PROPOSAL_STALE/);
  assert.equal((await row('select status from miyar_catalogue_requests where id=$1',[stale.id])).status,'pending');
  await decide(stale.id,false,'سبق تحديث السجل بطلب آخر');
  for(let i=0;i<2;i++)await propose(student,'doctor.correct',doctorId,1,'أحمد محمد العتيبي اقتراح '+i,false);
  await assert.rejects(propose(student,'doctor.correct',doctorId,1,'أحمد محمد العتيبي اقتراح زائد',false),/RATE_LIMIT/);
  const renameMajor=await propose(ambassador,'major.correct',majorId,collegeId,'الفيزياء التطبيقية');
  await decide(renameMajor.id,true);
  const renameCollege=await propose(ambassador,'college.correct',collegeId,null,'كلية العلوم التطبيقية');
  await decide(renameCollege.id,true);
  assert.equal((await row('select name from miyar_majors where id=$1',[majorId])).name,'الفيزياء التطبيقية');
  assert.equal((await row('select name from miyar_colleges where id=$1',[collegeId])).name,'كلية العلوم التطبيقية');
  const duplicate=await propose(ambassador,'college.add',null,null,'كلية الهندسة');
  await assert.rejects(decide(duplicate.id,true),/unique constraint/);
  assert.equal((await row('select status from miyar_catalogue_requests where id=$1',[duplicate.id])).status,'pending');
  await decide(duplicate.id,false,'الكلية مضافة بالفعل');
  const uniCollege=(await row("insert into miyar_colleges(name,university_id) values('كلية خارج الجامعة',1) returning id")).id;
  const uniMajor=(await row("insert into miyar_majors(name,college_id) values('تخصص خارج الجامعة',$1) returning id",[uniCollege])).id;
  const uniDoctor=(await row("insert into miyar_doctors(name,major_id,status) values('خالد محمد الحربي',$1,'approved') returning id",[uniMajor])).id;
  await assert.rejects(propose(ambassador,'major.add',null,uniCollege,'تخصص آخر'),/INVALID_MAJOR/);
  await assert.rejects(propose(ambassador,'doctor.correct',uniDoctor,1,'خالد محمد الحربي المصحح'),/PROPOSAL_TARGET_UNAVAILABLE/);
  await assert.rejects(propose(student,'doctor.correct',uniDoctor,1,'خالد محمد الحربي المصحح',false),/PROPOSAL_TARGET_UNAVAILABLE/);
  await rpc('miyar_set_ambassador',[admin,'ambassador@example.com',1,true]);
  const otherUniversity=await propose(ambassador,'college.add',null,null,'كلية السفير الأخرى',true,1);
  await decide(otherUniversity.id,true);
  assert.equal((await row("select university_id from miyar_colleges where name='كلية السفير الأخرى'")).university_id,1);
  await rpc('miyar_set_ambassador',[admin,'ambassador@example.com',1,false]);
  const used=(await row('select count(*)::int as n from miyar_catalogue_requests where account_id=$1',[ambassador])).n;
  for(let i=used;i<19;i++)await propose(ambassador,'college.add',null,null,'كلية مقترحة '+i);
  const revoked=await propose(ambassador,'college.add',null,null,'كلية الحاسب');
  await assert.rejects(propose(ambassador,'college.add',null,null,'كلية مقترحة زائدة'),/RATE_LIMIT/);
  await rpc('miyar_set_ambassador',[admin,'ambassador@example.com',3,false]);
  await assert.rejects(propose(ambassador,'college.add',null,null,'كلية الطب'),/AMBASSADOR_SCOPE/);
  await assert.rejects(decide(revoked.id,true),/AMBASSADOR_REVOKED/);
  await decide(revoked.id,false,'انتهت مهمة السفير');
  await db.query("update miyar_accounts set status='restricted' where auth_id=$1",[student]);
  await assert.rejects(propose(student,'doctor.correct',doctorId,1,'أحمد محمد العتيبي الصحيح',false),/ACCOUNT_RESTRICTED/);
  // Even direct browser RPC calls and role self-assignment are denied.
  for(const role of ['anon','authenticated']){
   await db.exec('set role '+role);
   for(const table of ['miyar_ambassadors','miyar_catalogue_requests'])await assert.rejects(db.query('select * from '+table),/permission denied/);
   await assert.rejects(rpc('miyar_set_ambassador',[student,'student@example.com',3,true]),/permission denied/);
   await assert.rejects(rpc('miyar_catalogue_queue'),/permission denied/);
   await assert.rejects(rpc('miyar_decide_catalogue',[student,1,true,'']),/permission denied/);
   await assert.rejects(rpc('miyar_propose_catalogue',[student,'college.add',3,null,null,'كلية خاصة','',true]),/permission denied/);
   await db.exec('reset role');
  }
  const publicData=JSON.stringify(await rpc('miyar_catalogue'));
  assert.ok(!publicData.includes('@example.com'));assert.ok(!publicData.includes(ambassador));
  await db.exec('set role service_role');
  assert.deepEqual(await rpc('miyar_ambassador_list'),[]);
  assert.ok((await rpc('miyar_my_requests',[ambassador])).length>0);
  assert.ok((await rpc('miyar_catalogue_queue')).length>0);
  await db.exec('reset role');
 }finally{await db.close();}
});

